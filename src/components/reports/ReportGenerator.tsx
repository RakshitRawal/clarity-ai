import React, { useRef } from 'react';
import {
  FileCheck2,
  Printer,
  Download,
  Share2,
  ShieldCheck,
  AlertOctagon,
  Calendar,
  FileText,
  Sparkles,
  Layers,
} from 'lucide-react';
import { ClarityDocument } from '../../types';
import { ClaimBadge, MethodBadge } from '../common/Badge';

interface ReportGeneratorProps {
  document: ClarityDocument;
}

export const ReportGenerator: React.FC<ReportGeneratorProps> = ({ document: docItem }) => {
  const reportRef = useRef<HTMLDivElement>(null);
  const summary = docItem.summaries[docItem.activeMethod];

  const handlePrint = () => {
    window.print();
  };

  const handleDownloadMarkdown = () => {
    if (!summary) return;
    const content = `# ClarityAI Document Audit Report: ${docItem.title}

Generated: ${new Date().toUTCString()}
Summarisation Method: ${summary.method}
Factual Consistency Rate: ${summary.metrics.factualConsistency.consistencyRate}%
Total Claims Analysed: ${summary.metrics.factualConsistency.totalClaims}
Supported Claims: ${summary.metrics.factualConsistency.supportedClaims}
Contradicted Claims: ${summary.metrics.factualConsistency.contradictedClaims}
Needs Review: ${summary.metrics.factualConsistency.unverifiedClaims}

## Generated Summary
${summary.text}

## Claim-by-Claim Verification
${summary.claims
  .map(
    (c, i) =>
      `### Claim ${i + 1}: ${c.claimText}
- **Status:** ${c.status.toUpperCase()}
- **Model Confidence:** ${(c.confidenceScore * 100).toFixed(0)}%
- **Location:** ${c.sourceLocation?.section || 'General'}
- **Analysis:** ${c.explanation}
- **Source Context:** "${c.supportingPassage || c.conflictingPassage || 'None'}"`
  )
  .join('\n\n')}

---
Report generated by ClarityAI (Public Document Summarisation Without Invented Facts).
Evidence behind every claim.`;

    const blob = new Blob([content], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = window.document.createElement('a');
    a.href = url;
    a.download = `ClarityAI_Audit_Report_${docItem.title.replace(/[^a-z0-9]/gi, '_')}.md`;
    window.document.body.appendChild(a);
    a.click();
    window.document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  if (!summary) {
    return (
      <div className="p-8 text-center text-slate-500">
        No summary analysis available for this document yet.
      </div>
    );
  }

  const fc = summary.metrics.factualConsistency;

  return (
    <div className="space-y-6">
      {/* Top Action Bar */}
      <div className="flex items-center justify-between gap-3 p-4 rounded-xl border border-slate-200 dark:border-slate-800 bg-white dark:bg-charcoal-900 shadow-sm">
        <div>
          <h3 className="text-sm font-bold text-slate-900 dark:text-white">
            Formal Document Verification Report
          </h3>
          <p className="text-xs text-slate-500 dark:text-slate-400">
            Exportable audit transcript for regulatory compliance and peer review
          </p>
        </div>

        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={handlePrint}
            className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-charcoal-800 text-xs font-semibold text-slate-700 dark:text-slate-200 hover:bg-slate-50 dark:hover:bg-charcoal-700 transition-colors"
          >
            <Printer className="w-3.5 h-3.5" />
            <span>Print / PDF</span>
          </button>
          <button
            type="button"
            onClick={handleDownloadMarkdown}
            className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-brand-600 hover:bg-brand-700 text-xs font-semibold text-white shadow-sm transition-colors"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download Markdown</span>
          </button>
        </div>
      </div>

      {/* Printable Report Document Card */}
      <div
        ref={reportRef}
        className="rounded-2xl border border-slate-200 dark:border-slate-800 bg-white dark:bg-charcoal-900 p-8 sm:p-12 shadow-md space-y-8 print:border-none print:shadow-none print:p-0"
      >
        {/* Document Header */}
        <div className="border-b border-slate-200 dark:border-slate-800 pb-6 flex flex-col sm:flex-row justify-between items-start gap-4">
          <div>
            <div className="flex items-center gap-2 mb-2">
              <span className="text-xs font-bold uppercase tracking-wider text-brand-600 dark:text-brand-400">
                ClarityAI Factual Audit Report
              </span>
              <span className="text-slate-300 dark:text-slate-700">•</span>
              <span className="text-xs text-slate-500 font-mono">
                ID: {docItem.id}
              </span>
            </div>
            <h2 className="text-2xl font-extrabold text-slate-900 dark:text-white tracking-tight">
              {docItem.title}
            </h2>
            <div className="flex flex-wrap items-center gap-3 mt-2 text-xs text-slate-500 dark:text-slate-400">
              <span>Category: {docItem.category || 'General Document'}</span>
              <span>•</span>
              <span>Word Count: {docItem.wordCount.toLocaleString()} words</span>
              <span>•</span>
              <span>Audited: {new Date(docItem.uploadedAt).toLocaleDateString()}</span>
            </div>
          </div>

          <div className="text-right flex sm:flex-col items-center sm:items-end gap-2">
            <MethodBadge method={summary.method} />
            <span className="text-xs font-mono text-slate-500">
              Compression: {(summary.compressionRatio * 100).toFixed(1)}%
            </span>
          </div>
        </div>

        {/* Executive Scorecard */}
        <div className="grid grid-cols-2 sm:grid-cols-4 gap-4 p-5 rounded-xl bg-slate-50 dark:bg-charcoal-950/60 border border-slate-200/80 dark:border-slate-800">
          <div>
            <span className="text-[11px] font-semibold text-slate-400 uppercase tracking-wider block mb-1">
              Factual Consistency
            </span>
            <div className="text-2xl font-extrabold text-slate-900 dark:text-white">
              {fc.consistencyRate}%
            </div>
          </div>
          <div>
            <span className="text-[11px] font-semibold text-slate-400 uppercase tracking-wider block mb-1">
              Supported Claims
            </span>
            <div className="text-2xl font-extrabold text-emerald-600 dark:text-emerald-400">
              {fc.supportedClaims} / {fc.totalClaims}
            </div>
          </div>
          <div>
            <span className="text-[11px] font-semibold text-slate-400 uppercase tracking-wider block mb-1">
              Contradicted Claims
            </span>
            <div className="text-2xl font-extrabold text-rose-600 dark:text-rose-400">
              {fc.contradictedClaims}
            </div>
          </div>
          <div>
            <span className="text-[11px] font-semibold text-slate-400 uppercase tracking-wider block mb-1">
              Flagged For Review
            </span>
            <div className="text-2xl font-extrabold text-amber-600 dark:text-amber-400">
              {fc.unverifiedClaims}
            </div>
          </div>
        </div>

        {/* Generated Summary Section */}
        <div className="space-y-3">
          <h4 className="text-sm font-bold uppercase tracking-wider text-slate-800 dark:text-slate-200">
            1. Audited Summary
          </h4>
          <div className="p-5 rounded-xl bg-slate-50 dark:bg-charcoal-950/60 border border-slate-200/70 dark:border-slate-800 text-sm leading-relaxed text-slate-800 dark:text-slate-200 font-serif">
            {summary.text}
          </div>
        </div>

        {/* Claim Verification Table */}
        <div className="space-y-3">
          <h4 className="text-sm font-bold uppercase tracking-wider text-slate-800 dark:text-slate-200">
            2. Detailed Claim Verification Audit
          </h4>

          <div className="rounded-xl border border-slate-200 dark:border-slate-800 overflow-hidden">
            <table className="w-full text-left text-xs">
              <thead className="bg-slate-100 dark:bg-charcoal-800 text-slate-700 dark:text-slate-300 font-semibold border-b border-slate-200 dark:border-slate-800">
                <tr>
                  <th className="p-3 pl-4">Claim</th>
                  <th className="p-3">Status</th>
                  <th className="p-3">Model Confidence</th>
                  <th className="p-3">Source Evidence</th>
                  <th className="p-3 pr-4">Auditor Note</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
                {summary.claims.map((claim, index) => (
                  <tr key={claim.id} className="hover:bg-slate-50/50 dark:hover:bg-charcoal-800/40">
                    <td className="p-3 pl-4 font-medium text-slate-900 dark:text-slate-100 max-w-xs">
                      {claim.claimText}
                    </td>
                    <td className="p-3 whitespace-nowrap">
                      <ClaimBadge status={claim.status} size="sm" />
                    </td>
                    <td className="p-3 font-mono">
                      {(claim.confidenceScore * 100).toFixed(0)}%
                    </td>
                    <td className="p-3 italic text-slate-600 dark:text-slate-400 font-serif max-w-sm">
                      "{claim.supportingPassage || claim.conflictingPassage || 'No direct span'}"
                    </td>
                    <td className="p-3 pr-4 text-slate-600 dark:text-slate-400">
                      {claim.explanation}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>

        {/* ROUGE Scores if available */}
        <div className="space-y-3">
          <h4 className="text-sm font-bold uppercase tracking-wider text-slate-800 dark:text-slate-200">
            3. Reference-Based Evaluation (ROUGE)
          </h4>

          {summary.metrics.hasReferenceSummary && summary.metrics.rouge ? (
            <div className="grid grid-cols-3 gap-4 p-4 rounded-xl border border-slate-200 dark:border-slate-800 bg-slate-50 dark:bg-charcoal-950/60 text-xs">
              <div>
                <span className="text-slate-400 font-semibold block mb-0.5">ROUGE-1 F1</span>
                <span className="text-lg font-bold font-mono text-slate-900 dark:text-white">
                  {(summary.metrics.rouge.rouge1.f1 * 100).toFixed(1)}%
                </span>
              </div>
              <div>
                <span className="text-slate-400 font-semibold block mb-0.5">ROUGE-2 F1 (Competition Metric)</span>
                <span className="text-lg font-bold font-mono text-brand-600 dark:text-brand-400">
                  {(summary.metrics.rouge.rouge2.f1 * 100).toFixed(1)}%
                </span>
              </div>
              <div>
                <span className="text-slate-400 font-semibold block mb-0.5">ROUGE-L F1</span>
                <span className="text-lg font-bold font-mono text-slate-900 dark:text-white">
                  {(summary.metrics.rouge.rougeL.f1 * 100).toFixed(1)}%
                </span>
              </div>
            </div>
          ) : (
            <div className="p-4 rounded-xl border border-dashed border-slate-300 dark:border-slate-800 text-xs text-slate-500 text-center">
              Reference summary required to calculate ROUGE-1, ROUGE-2, and ROUGE-L. No synthetic score fabricated.
            </div>
          )}
        </div>

        {/* Footer Disclaimer */}
        <div className="pt-6 border-t border-slate-200 dark:border-slate-800 flex flex-col sm:flex-row items-center justify-between text-[11px] text-slate-400 gap-2">
          <span>ClarityAI — Public Document Summarisation Without Invented Facts</span>
          <span>Verification is probabilistic review evidence, not an infallible legal finding</span>
        </div>
      </div>
    </div>
  );
};
